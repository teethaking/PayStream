#!/usr/bin/env node
// Generates typed ABIs from the Foundry artifact and records the Aevum deployment from the
// broadcast log. Only real on-chain output is written; nothing here is invented.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHAIN_ID = 44005;
const RPC = process.env.AEVUM_RPC_URL ?? 'https://rpc-test.qday.info';

const artifactPath = join(root, 'out/StreamVault.sol/StreamVault.json');
if (!existsSync(artifactPath)) {
  console.error('Missing Foundry artifact. Run `forge build` first.');
  process.exit(1);
}
const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'));

const header = '// Generated by scripts/sync-artifacts.mjs from out/StreamVault.sol/StreamVault.json. Do not edit.\n';
const abiTs = `${header}export const streamVaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
for (const target of ['packages/paystream-sdk/src/abi.ts', 'web/src/abi/streamVault.ts']) {
  const file = join(root, target);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, abiTs);
  console.log('wrote', target);
}

const broadcast = join(root, `broadcast/Deploy.s.sol/${CHAIN_ID}/run-latest.json`);
if (!existsSync(broadcast)) {
  console.log(`No Aevum broadcast found; deployments/aevum-${CHAIN_ID}.json left unchanged.`);
  process.exit(0);
}
const run = JSON.parse(readFileSync(broadcast, 'utf8'));
const tx = run.transactions.find((t) => t.contractName === 'StreamVault' && t.transactionType === 'CREATE');
const receipt = run.receipts.find((r) => r.transactionHash === tx.hash);
if (!tx || !receipt || receipt.status !== '0x1') {
  console.error('StreamVault CREATE transaction or successful receipt not found in broadcast log.');
  process.exit(1);
}

const rpc = async (method, params) => {
  const res = await fetch(RPC, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }),
  });
  const json = await res.json();
  if (json.error) throw new Error(json.error.message);
  return json.result;
};
const code = await rpc('eth_getCode', [tx.contractAddress, 'latest']);
if (!code || code === '0x') {
  console.error('No code at', tx.contractAddress, 'on chain', CHAIN_ID);
  process.exit(1);
}

const deployment = {
  chainId: CHAIN_ID,
  network: 'QDay Aevum testnet',
  streamVault: tx.contractAddress,
  token: '0x456569838f1d43009A91ebA4263147Afd7233483',
  deployer: tx.transaction.from,
  deployTxHash: tx.hash,
  deployBlock: Number(BigInt(receipt.blockNumber)),
  compiler: { solc: '0.8.28', evmVersion: 'shanghai', optimizer: true, runs: 200 },
};
const out = join(root, `deployments/aevum-${CHAIN_ID}.json`);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, JSON.stringify(deployment, null, 2) + '\n');
console.log('wrote', out, deployment);
